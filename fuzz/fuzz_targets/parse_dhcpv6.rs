// Fuzz du decodeur DHCPv6 : type de message, identifiant de transaction sur
// trois octets, options brutes. Ni panic ni boucle ; quand le decodage
// reussit, les options sont l'entree privee de ses quatre premiers octets,
// le type et l'identifiant sont ceux du fil, et l'affichage ne panique pas.
#![no_main]

#[path = "../oracles/seeds.rs"]
mod seeds;

use libfuzzer_sys::fuzz_target;
use packet_parser::parse::application::protocols::dhcpv6::Dhcpv6Packet;
use seeds::{inside, replay_mutated};

// dhcp6_outlease_acquisition.pcapng, trame 1 : Solicit.
const SOLICIT: &[u8] = &[
    0x01, 0x9d, 0xe0, 0x3f, 0x00, 0x01, 0x00, 0x0e, 0x00, 0x01, 0x00, 0x01, 0x1d, 0xef, 0x69, 0xbd,
    0x00, 0x0c, 0x29, 0x5e, 0x77, 0x44, 0x00, 0x06, 0x00, 0x08, 0x00, 0x17, 0x00, 0x18, 0x00, 0x27,
    0x00, 0x1f, 0x00, 0x08, 0x00, 0x02, 0x00, 0x00, 0x00, 0x03, 0x00, 0x0c, 0x29, 0x5e, 0x77, 0x44,
    0x00, 0x00, 0x0e, 0x10, 0x00, 0x00, 0x15, 0x18,
];

// dhcp6_outlease_acquisition.pcapng, trame 2 : Advertise, avec IA_NA.
const ADVERTISE: &[u8] = &[
    0x02, 0x9d, 0xe0, 0x3f, 0x00, 0x01, 0x00, 0x0e, 0x00, 0x01, 0x00, 0x01, 0x1d, 0xef, 0x69, 0xbd,
    0x00, 0x0c, 0x29, 0x5e, 0x77, 0x44, 0x00, 0x02, 0x00, 0x0e, 0x00, 0x01, 0x00, 0x01, 0x1d, 0xe4,
    0xb8, 0x58, 0x00, 0x0c, 0x29, 0x1f, 0xa7, 0x55, 0x00, 0x03, 0x00, 0x28, 0x29, 0x5e, 0x77, 0x44,
    0x00, 0x00, 0x07, 0x08, 0x00, 0x00, 0x0b, 0x40, 0x00, 0x05, 0x00, 0x18, 0x20, 0x01, 0x0d, 0xb8,
    0x00, 0x01, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x02, 0x00, 0x00, 0x0e, 0x10,
    0x00, 0x00, 0x0e, 0x10, 0x00, 0x17, 0x00, 0x10, 0x20, 0x01, 0x0d, 0xb8, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x35,
];

fn exercise(data: &[u8]) {
    let Ok(packet) = Dhcpv6Packet::try_from(data) else {
        return;
    };
    assert_eq!(packet.message_type, data[0]);
    assert_eq!(
        packet.transaction_id,
        u32::from_be_bytes([0, data[1], data[2], data[3]])
    );
    assert_eq!(packet.options.len() + 4, data.len());
    assert!(data.ends_with(packet.options) && inside(data, packet.options));
    let _ = packet.to_string();
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(&[SOLICIT, ADVERTISE], data, exercise);
});
