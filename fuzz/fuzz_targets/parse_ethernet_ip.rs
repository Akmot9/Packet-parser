// Synthetique, aucune capture du depot ne porte de RegisterSession :
// version 1, options nulles.
const REGISTER_SESSION: &[u8] = &[
    0x65, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
];

fn exercise(data: &[u8]) {
    let Ok(packet) = EtherNetIpPacket::try_from(data) else {
        return;
    };
    assert_eq!(usize::from(packet.header.length) + 24, data.len());
    assert_eq!(packet.header.sender_context, &data[12..20]);
    assert!(inside(data, packet.header.sender_context));
    assert!(!packet.header.command.name().is_empty());
    match &packet.command_data {
        EtherNetIpCommandData::Empty => assert_eq!(data.len(), 24),
        EtherNetIpCommandData::RegisterSession { .. } => assert_eq!(data.len(), 28),
        EtherNetIpCommandData::CommonPacketFormat(cpf) => {
            // Interface handle, timeout et nombre d'items, puis les items.
            let mut covered = 24 + 8;
            let mut count = 0;
            for item in cpf.items.iter() {
                assert!(inside(data, item.data));
                covered += 4 + item.data.len();
                count += 1;
            }
            assert_eq!(covered, data.len());
            assert_eq!(cpf.items.len(), count);
            assert_eq!(cpf.items.is_empty(), count == 0);
            assert_eq!(cpf.items.get(0).is_some(), count > 0);
            assert!(cpf.items.get(count).is_none());
            let _ = format!("{:?}", cpf.items);
        }
        EtherNetIpCommandData::Raw(raw) => {
            assert!(!raw.is_empty());
            assert_eq!(raw.len() + 24, data.len());
            assert!(inside(data, raw));
        }
        _ => {}
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(
        &[
            LIST_IDENTITY_REQUEST,
            LIST_IDENTITY_RESPONSE,
            REGISTER_SESSION,
            SEND_RR_DATA,
            SEND_UNIT_DATA,
        ],
        data,
        exercise,
    );
});
