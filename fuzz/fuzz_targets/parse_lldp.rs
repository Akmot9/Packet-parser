// Fuzz du decodeur LLDP (IEEE 802.1AB) : suite de TLV a longueur sur neuf
// bits, Chassis ID, Port ID et Time To Live obligatoires en tete, End of
// LLDPDU et bourrage, Management Address et TLV d'organisation. Ni panic ni
// boucle infinie ; quand le decodage reussit, les TLV et le bourrage pavent
// l'entree, chaque emprunt pointe dans l'entree ; la sonde aveugle de
// `Internet::try_from` ne reconnait jamais un LLDPDU que le decodeur refuse.
