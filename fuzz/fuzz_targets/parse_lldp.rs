fn within(data: &[u8], borrowed: &[u8]) -> bool {
    borrowed.is_empty() || data.as_ptr_range().contains(&borrowed.as_ptr())
}

fn exercise(data: &[u8]) {
    let Ok(packet) = LldpPacket::try_from(data) else {
        if let Ok(internet) = Internet::try_from(data) {
            assert_ne!(internet.protocol_name, "LLDP");
        }
        return;
    };
    let consumed: usize = packet.tlvs.iter().map(|tlv| 2 + tlv.value.len()).sum();
    assert_eq!(consumed + packet.padding.len(), data.len());
    assert!(packet.tlvs.len() >= 3 && packet.tlvs.len() <= data.len() / 2);
    for tlv in &packet.tlvs {
        assert!(within(data, tlv.value));
        let _ = (tlv.type_name(), tlv.as_text());
    }
    for id in [packet.chassis_id, packet.port_id] {
        assert!(!id.id.is_empty() && within(data, id.id));
        let _ = (id.as_text(), id.as_mac(), id.as_network_address());
    }
    let _ = (
        packet.time_to_live,
        packet.port_description(),
        packet.system_name(),
        packet.system_description(),
        packet.system_capabilities(),
    );
    for address in packet.management_addresses() {
        assert!(within(data, address.address) && within(data, address.oid));
        assert!(address.oid.len() <= 128);
        let _ = address.ip();
    }
    for organization in packet.organization_tlvs() {
        assert!(within(data, organization.info));
        let _ = organization.organization();
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);

    // Deux octets de fuzz choisissent une position et une mutation XOR sur
    // une graine reelle : types et longueurs de TLV, sous-types et
    // longueurs internes sont atteints des le depart.
    for seed in [SCALANCE, C2960] {
        let mut seeded = seed.to_vec();
        for [offset, mask] in data.as_chunks::<2>().0 {
            let offset = usize::from(*offset) % seeded.len();
            seeded[offset] ^= mask;
        }
        exercise(seeded.as_slice());
    }
});
