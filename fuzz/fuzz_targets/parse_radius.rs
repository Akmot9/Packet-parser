fn exercise(data: &[u8]) {
    let Ok(packet) = RadiusPacket::try_from(data) else {
        return;
    };
    assert_eq!(usize::from(packet.length), data.len());
    assert!((20..=4096).contains(&packet.length));
    let mut covered = 20;
    for attribute in &packet.attributes {
        assert!(attribute.length >= 2);
        assert_eq!(attribute.value.len(), usize::from(attribute.length) - 2);
        assert!(attribute.value.is_empty() || data.as_ptr_range().contains(&attribute.value.as_ptr()));
        let _ = (attribute.as_u32(), attribute.as_ipv4(), attribute.as_text());
        if attribute.kind == Some(AttributeType::VendorSpecific) {
            let _ = attribute.vendor();
        } else {
            assert_eq!(attribute.vendor(), None);
        }
        covered += usize::from(attribute.length);
    }
    assert_eq!(covered, data.len());
    let _ = packet.attribute(AttributeType::UserName);
}

fuzz_target!(|data: &[u8]| {
    exercise(data);

    // Deux octets de fuzz choisissent une position et une mutation XOR sur
    // une graine reelle : codes, longueurs et chaines d'attributs sont
    // atteints des le depart.
    for seed in [ACCESS_REQUEST, ACCESS_CHALLENGE, ACCESS_REJECT] {
        let mut seeded = seed.to_vec();
        for [offset, mask] in data.as_chunks::<2>().0 {
            let offset = usize::from(*offset) % seeded.len();
            seeded[offset] ^= mask;
        }
        exercise(seeded.as_slice());
    }
});
