// ndpi_line.pcap, trame 28 : un message de retour seul (RFC 5506).
const FEEDBACK: &[u8] = &[
    0x8b, 0xcd, 0x00, 0x0c, 0x00, 0x00, 0x1a, 0x92, 0x00, 0x00, 0x1a, 0x92, 0x00, 0x00, 0x01, 0xbb,
    0x00, 0x01, 0x00, 0xc9, 0x09, 0xbd, 0xa6, 0x74, 0x00, 0x08, 0x00, 0x02, 0xfc, 0xbc, 0xa0, 0xb8,
    0x20, 0x68, 0x60, 0x40, 0x09, 0xbd, 0xa6, 0x44, 0x00, 0x00, 0x00, 0x00, 0x09, 0xbd, 0xa6, 0x44,
    0x00, 0x00, 0x00, 0x00,
];

fn exercise(data: &[u8]) {
    let Ok(compound) = RtcpCompound::try_from(data) else {
        return;
    };
    assert_eq!(compound.as_bytes(), data);
    let mut total = 0usize;
    let mut padded = false;
    for packet in compound.packets() {
        // Rien ne suit un paquet a bourrage.
        assert!(!padded);
        padded = packet.padding;
        assert!(inside(data, packet.body));
        assert_eq!(packet.body.len() % 4, 0);
        assert!(packet.count < 32);
        assert!((200..=207).contains(&packet.packet_type.as_u8()));
        if let Some(info) = packet.sender_info() {
            assert_eq!(packet.packet_type, RtcpPacketType::SenderReport);
            let _ = (info.ntp_timestamp, info.rtp_timestamp, info.packet_count);
        }
        let _ = packet.sender_ssrc();
        total += RTCP_HEADER_LENGTH + packet.body.len();
    }
    assert_eq!(total, data.len());
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(&[SR_SDES_BYE, FEEDBACK], data, exercise);
});
