fn exercise_ike(data: &[u8]) {
    if let Ok(packet) = IkePacket::try_from(data) {
        assert_eq!(packet.header.length as usize, data.len());
        let major = packet.header.major_version();
        assert!(major == 1 || major == 2);
        if packet.header.encryption_flag() {
            assert!(packet.payloads.is_empty());
            assert_eq!(packet.encrypted_body.map(<[u8]>::len), Some(data.len() - 28));
        } else {
            let mut covered = 28;
            for payload in &packet.payloads {
                assert!(payload.length >= 4);
                assert_eq!(payload.body.len(), usize::from(payload.length) - 4);
                assert!(payload.body.is_empty() || data.as_ptr_range().contains(&payload.body.as_ptr()));
                covered += usize::from(payload.length);
            }
            assert_eq!(covered, data.len());
            let last_is_sk = packet
                .payloads
                .last()
                .is_some_and(|payload| major == 2 && matches!(payload.payload_type, 46 | 53));
            assert_eq!(packet.encrypted_body.is_some(), last_is_sk);
            if last_is_sk {
                assert_eq!(packet.encrypted_body, packet.payloads.last().map(|p| p.body));
            }
        }
    }
    let from_udp = IkePacket::from_udp(data);
    let raw = IkePacket::try_from(data);
    let marked = data
        .strip_prefix(&[0, 0, 0, 0])
        .filter(|rest| !rest.is_empty())
        .map(IkePacket::try_from);
    assert_eq!(from_udp.is_ok(), raw.is_ok() || marked.is_some_and(|m| m.is_ok()));
}

fn exercise_udp_encapsulation(data: &[u8]) {
    match UdpEncapsulation::classify(data) {
        Ok(UdpEncapsulation::Keepalive) => assert_eq!(data, [0xff]),
        Ok(UdpEncapsulation::Ike(rest)) => {
            assert_eq!(&data[..4], [0, 0, 0, 0]);
            assert_eq!(rest.len(), data.len() - 4);
            assert!(!rest.is_empty());
        }
        Ok(UdpEncapsulation::Esp(esp)) => {
            assert_eq!(esp, data);
            assert!(data.len() >= 8);
            assert_ne!(&data[..4], [0, 0, 0, 0]);
        }
        Ok(_) => unreachable!("variante inconnue"),
        Err(_) => assert!(data.len() < 8 || data == [0, 0, 0, 0]),
    }
}

fn exercise_esp(data: &[u8]) {
    match EspPacket::try_from(data) {
        Ok(esp) => {
            assert!(data.len() >= 8);
            assert_ne!(esp.spi, 0);
            assert_eq!(esp.payload.len(), data.len() - 8);
        }
        Err(_) => assert!(data.len() < 8 || data[..4] == [0, 0, 0, 0]),
    }
}

fn exercise(data: &[u8]) {
    exercise_ike(data);
    exercise_udp_encapsulation(data);
    exercise_esp(data);
}

fuzz_target!(|data: &[u8]| {
    exercise(data);

    // Deux octets de fuzz choisissent une position et une mutation XOR sur
    // une graine reelle : en-tetes, chaines de payloads, marqueur et SPI
    // sont atteints des le depart.
    for seed in [IKEV2_SA_INIT, IKEV1_MAIN_MODE, NAT_T_INFORMATIONAL, NAT_T_ESP] {
        let mut seeded = seed.to_vec();
        for [offset, mask] in data.as_chunks::<2>().0 {
            let offset = usize::from(*offset) % seeded.len();
            seeded[offset] ^= mask;
        }
        exercise(seeded.as_slice());
    }
});
