fn exercise(data: &[u8]) {
    let Ok(packet) = GoosePacket::try_from(data) else {
        return;
    };
    assert_eq!(usize::from(packet.length), data.len());
    let _ = packet.simulation_bit();
    let pdu = &packet.pdu;
    for text in [pdu.gocb_ref, pdu.data_set].into_iter().chain(pdu.go_id) {
        assert!(text.is_empty() || data.as_ptr_range().contains(&text.as_ptr()));
    }
    let _ = (
        pdu.timestamp.nanoseconds(),
        pdu.timestamp.leap_second_known(),
        pdu.timestamp.clock_failure(),
        pdu.timestamp.clock_not_synchronized(),
    );
    assert!(pdu.timestamp.nanoseconds() < 1_000_000_000);
    // Chaque element de allData occupe au moins deux octets.
    assert!(pdu.all_data.len() <= data.len() / 2);
    for element in &pdu.all_data {
        assert!(element.value.is_empty() || data.as_ptr_range().contains(&element.value.as_ptr()));
        let _ = (element.kind, element.as_bool());
    }
    if let Some(security) = pdu.security {
        assert!(security.is_empty() || data.as_ptr_range().contains(&security.as_ptr()));
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);

    // Deux octets de fuzz choisissent une position et une mutation XOR sur
    // une graine reelle : etiquettes, longueurs BER et types de allData
    // sont atteints des le depart.
    for seed in [F650, DEMO] {
        let mut seeded = seed.to_vec();
        for [offset, mask] in data.as_chunks::<2>().0 {
            let offset = usize::from(*offset) % seeded.len();
            seeded[offset] ^= mask;
        }
        exercise(seeded.as_slice());
    }
});
