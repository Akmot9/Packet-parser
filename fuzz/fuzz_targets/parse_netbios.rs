fn check_name(name: &NetbiosName) {
    let trimmed = name.trimmed();
    assert!(trimmed.len() <= 15);
    if let Some(text) = name.as_str() {
        assert_eq!(text.as_bytes(), trimmed);
    }
}

fn exercise(data: &[u8]) {
    if let Ok(packet) = NbnsPacket::try_from(data) {
        assert_eq!(
            packet.transaction_id,
            u16::from_be_bytes([data[0], data[1]])
        );
        assert_eq!(packet.questions.len(), usize::from(packet.question_count));
        assert_eq!(
            packet.resource_records.len(),
            usize::from(packet.answer_count)
                + usize::from(packet.authority_count)
                + usize::from(packet.additional_count)
        );
        for question in &packet.questions {
            assert!(inside(data, question.scope));
            check_name(&question.name);
        }
        for record in &packet.resource_records {
            assert!(inside(data, record.scope) && inside(data, record.rdata));
            check_name(&record.name);
        }
    }

    if let Ok(packet) = NbssPacket::try_from(data) {
        assert_eq!(packet.header.message_type.code(), data[0]);
        assert_eq!(packet.payload.len(), packet.header.length as usize);
        assert!(packet.payload.len() + 4 <= data.len());
        assert!(inside(data, packet.payload));
    }

    if let Ok(packet) = NbdsPacket::try_from(data) {
        // Les sept types de la RFC 1002, quartet haut des drapeaux nul.
        assert_eq!(packet.message_type.code(), data[0]);
        assert!((0x10..=0x16).contains(&data[0]));
        assert_eq!(data[1] & 0xf0, 0);
        let flags = (packet.flags.node_type << 2)
            | (u8::from(packet.flags.first) << 1)
            | u8::from(packet.flags.more);
        assert_eq!(flags, data[1]);
        assert_eq!(packet.datagram_id.to_be_bytes(), data[2..4]);
        assert_eq!(packet.source_ip.octets(), data[4..8]);
        assert_eq!(packet.source_port.to_be_bytes(), data[8..10]);
        match packet.body {
            NbdsBody::Datagram(datagram) => {
                assert!((0x10..=0x12).contains(&data[0]));
                assert_eq!(datagram.length.to_be_bytes(), data[10..12]);
                assert_eq!(datagram.packet_offset.to_be_bytes(), data[12..14]);
                // La longueur annoncee est celle de l'entree, et les deux
                // noms (label de 33 octets, scope, octet nul) et les donnees
                // la pavent.
                assert_eq!(usize::from(datagram.length) + 14, data.len());
                for field in [
                    datagram.source_scope,
                    datagram.destination_scope,
                    datagram.user_data,
                ] {
                    assert!(inside(data, field));
                }
                assert_eq!(
                    68 + datagram.source_scope.len()
                        + datagram.destination_scope.len()
                        + datagram.user_data.len(),
                    usize::from(datagram.length)
                );
                check_name(&datagram.source_name);
                check_name(&datagram.destination_name);
            }
            NbdsBody::Error { code, .. } => {
                assert_eq!(data[0], 0x13);
                assert_eq!(data.len(), 11);
                assert_eq!(code, data[10]);
            }
            NbdsBody::Query {
                destination_name,
                destination_scope,
                ..
            } => {
                assert!((0x14..=0x16).contains(&data[0]));
                assert!(inside(data, destination_scope));
                assert_eq!(data.len(), 10 + 34 + destination_scope.len());
                check_name(&destination_name);
            }
            _ => {}
        }
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(
        &[REGISTRATION, NAME_QUERY, SESSION_MESSAGE, DATAGRAM],
        data,
        exercise,
    );
});
