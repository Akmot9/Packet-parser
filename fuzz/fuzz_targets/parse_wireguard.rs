fn inside(input: &[u8], field: &[u8]) -> bool {
    field.is_empty() || input.as_ptr_range().contains(&field.as_ptr())
}

fn exercise(data: &[u8]) {
    let blind = Application::try_from(data)
        .is_ok_and(|application| application.application_protocol == "WireGuard");
    let Ok(packet) = WireGuardPacket::try_from(data) else {
        assert!(!blind, "etiquete WireGuard sans se decoder");
        return;
    };
    assert_eq!(packet.message_type, data[0]);
    if blind {
        assert_eq!(packet.reserved, [0; 3]);
    }
    match &packet.message {
        WireGuardMessage::HandshakeInitiation(m) => {
            assert_eq!(data.len(), 148);
            for field in [
                &m.unencrypted_ephemeral[..],
                m.encrypted_static,
                m.encrypted_timestamp,
                m.mac1,
                m.mac2,
            ] {
                assert!(inside(data, field));
            }
        }
        WireGuardMessage::HandshakeResponse(m) => {
            assert_eq!(data.len(), 92);
            for field in [
                &m.unencrypted_ephemeral[..],
                m.encrypted_nothing,
                m.mac1,
                m.mac2,
            ] {
                assert!(inside(data, field));
            }
        }
        WireGuardMessage::CookieReply(m) => {
            assert_eq!(data.len(), 64);
            assert!(inside(data, m.nonce) && inside(data, m.encrypted_cookie));
        }
        WireGuardMessage::TransportData(m) => {
            assert!(data.len() >= 32);
            assert_eq!(m.encrypted_packet.len(), data.len() - 16);
            assert!(inside(data, m.encrypted_packet));
            assert_eq!(m.is_keepalive(), data.len() == 32);
        }
        _ => {}
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);

    // Deux octets de fuzz choisissent une position et une mutation XOR sur
    // une graine reelle : type, reserves, compteur et taille sont atteints
    // des le depart.
    for seed in [INITIATION, DATA, KEEPALIVE] {
        let mut seeded = seed.to_vec();
        for [offset, mask] in data.as_chunks::<2>().0 {
            let offset = usize::from(*offset) % seeded.len();
            seeded[offset] ^= mask;
        }
        exercise(seeded.as_slice());
    }
});
