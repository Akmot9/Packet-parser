/// L'etiquette et la longueur relues a la main : le numero de l'etiquette
/// d'application et la longueur annoncee, en-tete compris.
fn envelope(data: &[u8]) -> Option<(u8, usize)> {
    let (tag, first) = (*data.first()?, *data.get(1)?);
    if tag & 0xe0 != 0x60 {
        return None;
    }
    if first < 0x80 {
        return Some((tag & 0x1f, 2 + usize::from(first)));
    }
    let count = usize::from(first & 0x7f);
    if count == 0 || count > 4 {
        return None;
    }
    let length = data
        .get(2..2 + count)?
        .iter()
        .fold(0u64, |length, octet| (length << 8) | u64::from(*octet));
    // Au plus ce qu'un enregistrement de TCP annonce, sur 31 bits.
    if length > 0x7fff_ffff {
        return None;
    }
    Some((tag & 0x1f, 2 + count + usize::try_from(length).ok()?))
}

fn check_name(data: &[u8], name: Option<KerberosPrincipalName<'_>>) {
    let Some(name) = name else { return };
    let mut total = 0;
    for component in name.components() {
        assert!(inside(data, component));
        // Chaque composante a deux octets d'en-tete au moins.
        total += component.len() + 2;
    }
    assert!(total <= data.len());
}

fn check_message(data: &[u8], message: &KerberosMessage<'_>) {
    let (number, length) = envelope(data).expect("enveloppe que l'oracle ne lit pas");
    let code = message.message_type.code();
    assert_eq!(code, number);
    assert!(matches!(code, 10..=15 | 20..=22 | 30));
    assert_eq!(message.wire_length(), length);
    // En-tete minimal : deux etiquettes, pvno et msg-type.
    assert!(length >= 14 && data.len() >= 14);
    assert_eq!(message.is_truncated(), length > data.len());
    assert!(inside(data, message.rest()));
    assert_eq!(message.rest().len(), data.len().saturating_sub(length));

    // pvno et msg-type : [1] et [2] dans un KDC-REQ, [0] et [1] ailleurs.
    let is_request = matches!(
        message.message_type,
        KerberosMessageType::AsReq | KerberosMessageType::TgsReq
    );
    let first = u8::from(is_request);
    assert_eq!(message.field(first), Some(&[0x02, 0x01, 0x05][..]));
    assert_eq!(message.field(first + 1), Some(&[0x02, 0x01, code][..]));
    if is_request {
        assert_eq!(message.field(0), None);
    }
    for number in 0..=31 {
        if let Some(field) = message.field(number) {
            assert!(inside(data, field));
        }
    }

    for realm in [message.realm(), message.client_realm()]
        .into_iter()
        .flatten()
    {
        assert!(inside(data, realm));
    }
    check_name(data, message.client_name());
    check_name(data, message.service_name());
    let is_error = message.message_type == KerberosMessageType::Error;
    let is_reply = matches!(
        message.message_type,
        KerberosMessageType::AsRep | KerberosMessageType::TgsRep
    );
    assert!(message.error_code().is_none() || is_error);
    assert!(message.client_realm().is_none() || is_error || is_reply);
    if !(is_request || is_reply || is_error) {
        assert!(message.realm().is_none());
        assert!(message.client_name().is_none() && message.service_name().is_none());
    }
}

fn exercise(data: &[u8]) {
    if let Ok(message) = KerberosMessage::try_from(data) {
        check_message(data, &message);
    }

    // Les enregistrements de TCP : l'iterateur rend ce que des `try_from`
    // enchaines rendent, et s'arrete a la premiere erreur ou a la fin.
    let mut rest = data;
    for record in KerberosRecord::records(data) {
        assert_eq!(record, KerberosRecord::try_from(rest));
        let Ok(record) = record else {
            rest = &[];
            continue;
        };
        let message = &rest[4..];
        check_message(message, &record.message);
        assert_eq!(record.length.to_be_bytes(), rest[..4]);
        // Bit reserve nul, et au moins le plus court message (14 octets).
        assert!((14..0x8000_0000).contains(&record.length));
        assert_eq!(record.length as usize, record.message.wire_length());
        assert_eq!(record.is_truncated(), record.message.is_truncated());
        assert!(inside(rest, record.rest()));
        // Un enregistrement coupe est le dernier.
        assert!(!record.is_truncated() || record.rest().is_empty());
        assert!(record.rest().len() < rest.len());
        rest = record.rest();
    }
    assert!(rest.is_empty());
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(
        &[AS_REQUEST, ERROR, CUT_AS_REPLY, TCP_AS_REQUEST],
        data,
        exercise,
    );
});
