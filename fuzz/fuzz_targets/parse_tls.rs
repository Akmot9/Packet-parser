// Fuzz du decodeur TLS (couche record) : type de contenu, version, longueur,
// et `parse_tls_records` qui enchaine les records d'un segment. Ni panic ni
// boucle ; `looks_like_tls` rend le verdict de `try_from`, la liste des
// records est vide exactement quand le premier ne se decode pas, et les
// records rendus se suivent sans trou depuis le debut de l'entree, chacun
