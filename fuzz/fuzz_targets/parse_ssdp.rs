fn exercise(data: &[u8]) {
    let Ok(packet) = SsdpPacket::try_from(data) else {
        return;
    };
    let headers = [
        packet.man,
        packet.mx,
        packet.st,
        packet.nt,
        packet.nts,
        packet.usn,
        packet.location,
        packet.server,
    ];
    for value in headers.into_iter().flatten() {
        assert!(inside(data, value.as_bytes()));
    }
    if packet.message_type == SsdpMessageType::MSearch {
        assert!(packet.man.is_some());
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(&[M_SEARCH, NOTIFY], data, exercise);
});
