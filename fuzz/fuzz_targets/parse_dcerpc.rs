fn exercise(data: &[u8]) {
    let Ok(pdu) = DceRpcPdu::try_from(data) else {
        return;
    };
    assert_eq!(data[0], 5);
    assert!(pdu.version_minor <= 1);
    assert_eq!(pdu.pdu_type.as_u8(), data[2]);
    assert_eq!(pdu.flags, data[3]);
    assert_eq!(pdu.little_endian, data[4] >> 4 == 1);
    assert_eq!(pdu.data_representation, data[4..8]);
    assert!(inside(data, pdu.body));
    assert!(inside(data, pdu.rest()));
    assert_eq!(
        DCERPC_COMMON_HEADER_LENGTH + pdu.body.len() + pdu.rest().len(),
        data.len()
    );
    let fragment = usize::from(pdu.frag_length);
    assert!(DCERPC_COMMON_HEADER_LENGTH + pdu.body.len() <= fragment);
    // Une suite n'existe que derriere un fragment complet.
    assert!(pdu.rest().is_empty() || !pdu.is_truncated());
    assert!(usize::from(pdu.auth_length) < fragment);
    // Un refus de liaison porte au moins son motif de rejet.
    assert!(pdu.pdu_type != DceRpcPduType::BindNak || fragment >= DCERPC_COMMON_HEADER_LENGTH + 2);
    if let Some(request) = pdu.request() {
        assert_eq!(pdu.pdu_type, DceRpcPduType::Request);
        assert!(pdu.body.len() >= 8);
        let _ = (request.alloc_hint, request.context_id, request.opnum);
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(&[BIND, REQUEST], data, exercise);
});
