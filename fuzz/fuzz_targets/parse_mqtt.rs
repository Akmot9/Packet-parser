// Fuzz du decodeur MQTT (3.1.1 et 5) : en-tete fixe, Remaining Length en
// varint, en-tete variable propre a chaque type, paquets enchaines dans un
// meme segment. Ni panic ni boucle ; quand le decodage reussit, l'en-tete
// variable et le payload du premier paquet font ensemble sa Remaining
// Length, pointent dans l'entree, et l'affichage ne panique pas.
#![no_main]

#[path = "../oracles/seeds.rs"]
mod seeds;

use libfuzzer_sys::fuzz_target;
use packet_parser::parse::application::protocols::mqtt::MqttPacket;
use seeds::{inside, replay_mutated};

// mqtt_packets_tcpdump.pcap, trame 1 : CONNECT.
const CONNECT: &[u8] = &[
    0x10, 0x25, 0x00, 0x06, 0x4d, 0x51, 0x49, 0x73, 0x64, 0x70, 0x03, 0x02, 0x00, 0x05, 0x00, 0x17,
    0x70, 0x61, 0x68, 0x6f, 0x2f, 0x33, 0x34, 0x41, 0x41, 0x45, 0x35, 0x34, 0x41, 0x37, 0x35, 0x44,
    0x38, 0x33, 0x39, 0x35, 0x36, 0x36, 0x45,
];

// mqtt_packets_tcpdump.pcap, trame 3 : SUBSCRIBE, un filtre.
const SUBSCRIBE: &[u8] = &[
    0x82, 0x10, 0x00, 0x01, 0x00, 0x0b, 0x53, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x54, 0x6f, 0x70, 0x69,
    0x63, 0x00,
];

// mqtt_packets_tcpdump.pcap, trame 5 : PUBLISH.
const PUBLISH: &[u8] = &[
    0x31, 0x30, 0x00, 0x0b, 0x53, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x54, 0x6f, 0x70, 0x69, 0x63, 0x48,
    0x65, 0x6c, 0x6c, 0x6f, 0x20, 0x66, 0x72, 0x6f, 0x6d, 0x20, 0x74, 0x68, 0x65, 0x20, 0x50, 0x61,
    0x68, 0x6f, 0x20, 0x62, 0x6c, 0x6f, 0x63, 0x6b, 0x69, 0x6e, 0x67, 0x20, 0x63, 0x6c, 0x69, 0x65,
    0x6e, 0x74,
];

// mqtt_packets_tcpdump.pcap, trame 9 : PUBLISH puis DISCONNECT, un seul segment.
const PUBLISH_DISCONNECT: &[u8] = &[
    0x30, 0x17, 0x00, 0x0b, 0x53, 0x61, 0x6d, 0x70, 0x6c, 0x65, 0x54, 0x6f, 0x70, 0x69, 0x63, 0x48,
    0x65, 0x6c, 0x6c, 0x6f, 0x20, 0x4d, 0x51, 0x54, 0x54, 0xe0, 0x00,
];

fn exercise(data: &[u8]) {
    let Ok(packet) = MqttPacket::try_from(data) else {
        return;
    };
    let remaining = packet.fixed_header.remaining_length as usize;
    assert!(remaining <= 268_435_455);
    // Au moins deux octets d'en-tete fixe devant le corps.
    assert!(remaining + 2 <= data.len());
    assert_eq!(
        packet.variable_header.len() + packet.payload.len(),
        remaining
    );
    assert!(inside(data, packet.variable_header) && inside(data, packet.payload));
    let _ = (packet.to_string(), packet.fixed_header.to_string());
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(
        &[CONNECT, SUBSCRIBE, PUBLISH, PUBLISH_DISCONNECT],
        data,
        exercise,
    );
});
