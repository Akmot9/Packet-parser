/// Les versions d'en-tete que le decodeur admet.
const HEADER_VERSIONS: [u32; 11] = [0, 10, 11, 15, 16, 17, 18, 19, 20, 21, 22];

fn check(data: &[u8], message: &SkinnyMessage<'_>) {
    assert_eq!(message.data_length.to_le_bytes(), data[..4]);
    assert_eq!(message.header_version.to_le_bytes(), data[4..8]);
    assert_eq!(message.message_id.to_le_bytes(), data[8..12]);
    assert!(message.data_length >= 4);
    assert!(HEADER_VERSIONS.contains(&message.header_version));
    assert!(inside(data, message.body));
    assert!(inside(data, message.rest()));
    assert_eq!(
        SKINNY_HEADER_LENGTH + message.body.len() + message.rest().len(),
        data.len()
    );
    // Le corps ne depasse jamais la longueur annoncee, et la suite n'existe
    // que derriere un message complet.
    let announced = u64::from(message.data_length) - 4;
    let body = message.body.len() as u64;
    assert!(body <= announced);
    assert_eq!(message.is_truncated(), body < announced);
    assert!(message.rest().is_empty() || !message.is_truncated());
}

fn exercise(data: &[u8]) {
    let first = SkinnyMessage::try_from(data);
    if let Ok(message) = &first {
        check(data, message);
    }

    // L'iterateur : au plus un element par douze octets, les memes messages
    // que des `try_from` enchaines, et rien apres une erreur.
    let mut rest = data;
    let mut count = 0usize;
    let mut failed = false;
    for item in SkinnyMessage::messages(data) {
        assert!(!failed, "un element apres une erreur");
        assert!(!rest.is_empty());
        count += 1;
        assert_eq!(item, SkinnyMessage::try_from(rest));
        match item {
            Ok(message) => {
                check(rest, &message);
                rest = message.rest();
            }
            Err(_) => failed = true,
        }
    }
    assert!(failed || rest.is_empty());
    assert!(count <= data.len() / SKINNY_HEADER_LENGTH + 1);
    assert_eq!(count == 0, data.is_empty());
    if count > 0 {
        assert_eq!(
            first.is_ok(),
            SkinnyMessage::messages(data)
                .next()
                .is_some_and(|item| item.is_ok())
        );
    }
}

fuzz_target!(|data: &[u8]| {
    exercise(data);
    replay_mutated(&[REGISTER_ACK, TWO_MESSAGES], data, exercise);
});
